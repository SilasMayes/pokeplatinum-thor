#!/usr/bin/env python3
"""gen_migrate_table.py LAYOUT_JSON OUT_H

Writes src/port/save_migrate_v1_runs.h: the copy runs that move each save structure that changed from the
port's first layout (64-bit members 8-aligned) to the DS's. LAYOUT_JSON holds both layouts, as
dump_layout.py writes them from each build's DWARF:

    T=SystemData,Daycare,PCBoxes,BattleRecording
    LAYOUT_TYPES=$T LAYOUT_OUT=old.json gdb -batch -x dump_layout.py <Linux build of ba95fac5>/main
    LAYOUT_TYPES=$T LAYOUT_OUT=new.json gdb -batch -x dump_layout.py build_linux/main
    python3 -c "import json; json.dump({'old': json.load(open('old.json')), 'new': json.load(open('new.json'))}, open('layout.json', 'w'))"

Which structures changed: every save chunk's layout compared between the port build and a -m32 build
(64-bit members on 4-byte boundaries, as on the DS); after the change all of them match, and the totals
match PKHeX's Platinum block sizes (0xCF2C / 0x121E4) and offsets. Adapted from pokeheartgold's tool.
"""
import json, sys
L = json.load(open(sys.argv[1]))
OLD, NEW = L['old'], L['new']

# A member whose layout didn't change is copied whole, padding included: some padding is inside a checksum or
# a cipher stream (the battle video's encrypted part, for one), so it has to stay byte for byte.
def runs(old, new, oofs=0, nofs=0, out=None):
    out = [] if out is None else out
    if old == new:
        out.append((oofs, nofs, old['size']))
    elif old['kind'] == 'struct':
        nf = {f['name']: f for f in new['fields']}
        for f in old['fields']:
            g = nf[f['name']]
            if f['type']['kind'] == 'bits':
                o0, o1 = f['bitpos'] // 8, (f['bitpos'] + f['bitsize'] + 7) // 8
                out.append((oofs + o0, nofs + g['bitpos'] // 8, o1 - o0))
            else:
                runs(f['type'], g['type'], oofs + f['bitpos'] // 8, nofs + g['bitpos'] // 8, out)
    elif old['kind'] == 'array':
        for i in range(old['count']):
            runs(old['elem'], new['elem'], oofs + i * old['elem']['size'], nofs + i * new['elem']['size'], out)
    else:
        out.append((oofs, nofs, min(old['size'], new['size'])))
    return out

def merged(name):
    m = []
    for o, n, l in sorted(runs(OLD[name], NEW[name])):
        if m and o <= m[-1][0] + m[-1][2] and o - m[-1][0] == n - m[-1][1]:
            m[-1][2] = max(m[-1][2], o + l - m[-1][0])
        else:
            assert not m or o >= m[-1][0] + m[-1][2], (name, o)
            m.append([o, n, l])
    return m

CHUNK = {'SystemData': 'SAVE_TABLE_ENTRY_SYSTEM', 'Daycare': 'SAVE_TABLE_ENTRY_DAYCARE',
         'PCBoxes': 'SAVE_TABLE_ENTRY_PC_BOXES', 'BattleRecording': '-1 /* the battle videos (extra entries 2-5) */'}
out = ['// Generated by tools/port/save_layout/gen_migrate_table.py from the DWARF of the port builds before and',
       '// after the save took the DS layout (pokeplatinum-thor ba95fac5 and the commit that added this file). Do not edit.',
       '',
       'typedef struct PortSaveRun {', '    u32 oldOffset;', '    u32 newOffset;', '    u32 length;', '} PortSaveRun;', '']
table = []
for name in OLD:
    rs = merged(name)
    out.append(f'static const PortSaveRun sRuns_{name}[] = {{')
    out += [f'    {{ {o}, {n}, {l} }},' for o, n, l in rs]
    out.append('};')
    table.append(f'    {{ {CHUNK[name]}, {OLD[name]["size"]}, {NEW[name]["size"]}, sRuns_{name}, NELEMS(sRuns_{name}) }},')
out += ['', 'typedef struct PortSaveChangedStruct {', '    int chunk; // the save table entry, or -1 for the battle videos',
        '    u32 oldSize;', '    u32 newSize;', '    const PortSaveRun *runs;', '    int numRuns;', '} PortSaveChangedStruct;', '',
        'static const PortSaveChangedStruct sChangedStructs[] = {'] + table + ['};', '']
open(sys.argv[2], 'w').write('\n'.join(out))
print('runs:', {n: len(merged(n)) for n in OLD})
